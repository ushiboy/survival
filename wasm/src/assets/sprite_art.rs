// Crab (SPR_CRAB: 1 black, 2 red, 3 white)

pub fn crab_frames() -> [PixelArt; 2] {
    const BODY: [&str; 12] = [
        "................",
        "................",
        "................",
        "..111......111..",
        ".12221....12221.",
        ".1221.1..1.1221.",
        "..11.131131.11..",
        "...1112222111...",
        "..122222222221..",
        ".12222222222221.",
        ".12222222222221.",
        "..122222222221..",
    ];
    let make = |legs: [&'static str; 4]| {
        let mut rows: Vec<&str> = BODY.to_vec();
        rows.extend_from_slice(&legs);
        PixelArt::parse(&rows)
    };
    [
        make([".1.1111111111.1.", "1.1.1......1.1.1", "................", "................"]),
        make(["1..1111111111..1", ".1.1........1.1.", "................", "................"]),
    ]
}

