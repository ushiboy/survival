/// One segment of a gauge, filled with palette index `ink`.
pub fn gauge_segment(ink: u8, full: bool) -> PixelArt {
    let mut a = PixelArt::filled(8, 8, 0);
    for y in 2..6 {
        for x in 0..7 {
            let edge = x == 0 || x == 6 || y == 2 || y == 5;
            if full || edge {
                a.set(x, y, ink);
            }
        }
    }
    a
}
