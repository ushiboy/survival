// ---------------------------------------------------------------- vegetation (BG_VEG: 1 dark green, 2 light green, 3 sand, 0 black)

pub fn grass_plain() -> PixelArt {
    let mut a = PixelArt::filled(16, 16, 2);
    for &(x, y) in &[(2, 2), (10, 4), (5, 9), (13, 11), (1, 13)] {
        a.stamp(&["1.1", ".1."], x, y);
    }
    a
}

pub fn grass_tufts() -> PixelArt {
    let mut a = PixelArt::filled(16, 16, 2);
    for &(x, y) in &[(6, 1), (1, 6), (11, 7), (7, 12)] {
        a.stamp(&["1.1.1", ".1.1."], x, y);
    }
    a.stamp(&["1"], 14, 2);
    a.stamp(&["1"], 3, 14);
    a
}

