//! Background artwork (16x16 metatiles). Index meaning depends on the palette
//! the tile is drawn with — see `palettes.rs`.

use crate::ppu::pattern::PixelArt;

// ---------------------------------------------------------------- water

/// Deep water (BG_DEEP: 1 navy, 2 blue, 3 light blue). Two frames of drifting swell.
pub fn deep_water_frames() -> Vec<PixelArt> {
    const WAVE_A: [&str; 2] = [".333..", "3...11"];
    const WAVE_B: [&str; 2] = ["..333.", "13...1"];
    const SPOTS: [(i32, i32); 4] = [(1, 2), (9, 6), (3, 10), (10, 13)];
    const TROUGHS: [(i32, i32); 4] = [(13, 1), (6, 4), (0, 14), (8, 11)];

    (0..2)
        .map(|f| {
            let mut a = PixelArt::filled(16, 16, 2);
            for &(x, y) in &TROUGHS {
                a.stamp(&["1"], x + f, y);
            }
            for &(x, y) in &SPOTS {
                if f == 0 {
                    a.stamp(&WAVE_A, x, y);
                } else {
                    a.stamp(&WAVE_B, x, y);
                }
            }
            a
        })
        .collect()
}

/// Shallow water (BG_SHORE: 1 light blue, 2 white, 3 sand). Sandy specks on the
/// sea floor plus glints that move between frames.
pub fn shallow_water_frames() -> Vec<PixelArt> {
    const SEABED: [(i32, i32); 5] = [(2, 5), (11, 3), (7, 12), (14, 10), (4, 14)];
    const GLINT_A: [(i32, i32); 3] = [(4, 2), (12, 8), (1, 10)];
    const GLINT_B: [(i32, i32); 3] = [(6, 3), (10, 7), (2, 12)];

    (0..2)
        .map(|f| {
            let mut a = PixelArt::filled(16, 16, 1);
            for &(x, y) in &SEABED {
                a.stamp(&["3"], x, y);
            }
            let glints = if f == 0 { &GLINT_A } else { &GLINT_B };
            for &(x, y) in glints {
                a.stamp(if f == 0 { &["22"] } else { &["2.2"] }, x, y);
            }
            a
        })
        .collect()
}

// ---------------------------------------------------------------- sand (BG_SAND: 1 sand, 2 orange, 3 brown, 0 black)

pub fn sand_plain() -> PixelArt {
    let mut a = PixelArt::filled(16, 16, 1);
    for &(x, y) in &[(3, 1), (12, 6), (6, 9), (2, 12), (13, 13), (9, 3)] {
        a.stamp(&["2"], x, y);
    }
    for &(x, y) in &[(11, 2), (1, 6), (10, 11), (7, 14)] {
        a.stamp(&["3"], x, y);
    }
    a
}

pub fn sand_ripple() -> PixelArt {
    let mut a = PixelArt::filled(16, 16, 1);
    a.stamp(&["2222", "....22"], 3, 2);
    a.stamp(&["..2222", "22....2"], 8, 9);
    a.stamp(&["2"], 2, 11);
    a.stamp(&["3"], 4, 14);
    a.stamp(&["3"], 13, 5);
    a
}

